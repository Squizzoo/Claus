'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onAlert: (cb) => ipcRenderer.on('alert', (_e, a) => cb(a)),
  onCelebrate: (cb) => ipcRenderer.on('celebrate', (_e, c) => cb(c)),
  togglePanel: (wantedHeight) => ipcRenderer.send('toggle-panel', wantedHeight),
  panelHeight: (h) => ipcRenderer.send('panel-height', h),
  collapse: () => ipcRenderer.send('collapse'),
  painted: (id) => ipcRenderer.send('painted', id),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragMove: () => ipcRenderer.send('drag-move'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  jump: (id) => ipcRenderer.send('jump', id),
  dismiss: (id) => ipcRenderer.send('dismiss', id),
  rowMenu: (id) => ipcRenderer.send('row-menu', id),
  clearFinished: () => ipcRenderer.send('clear-finished'),
  clearIdle: () => ipcRenderer.send('clear-idle'),
  undo: () => ipcRenderer.send('undo'),
  unhide: () => ipcRenderer.send('unhide'),
  setPrefs: (patch) => ipcRenderer.send('set-prefs', patch),
  // the settings window (double-click the pet, or the tray)
  openSettings: () => ipcRenderer.send('open-settings'),
  clearProjectLook: (key) => ipcRenderer.send('clear-project-look', key),
  onSettingsState: (cb) => ipcRenderer.on('settings-state', (_e, s) => cb(s)),
  setLook: (patch) => ipcRenderer.send('set-look', patch),
  setBehaviour: (patch) => ipcRenderer.send('set-behaviour', patch),
  previewSound: (req) => ipcRenderer.send('preview-sound', req),
  setNotify: (patch) => ipcRenderer.send('set-notify', patch),
  snooze: (minutes) => ipcRenderer.send('snooze', minutes),
  setPlace: (patch) => ipcRenderer.send('set-place', patch),
  petGrab: () => ipcRenderer.send('pet-grab'),
  petMenu: () => ipcRenderer.send('pet-menu'),
  setSystem: (patch) => ipcRenderer.send('set-system', patch),
  hooksAction: (action) => ipcRenderer.send('hooks-action', action),
  chooseVersion: (version) => ipcRenderer.send('choose-version', version),
  wslHooksAction: (action) => ipcRenderer.send('wsl-hooks-action', action),
  updateAction: (what) => ipcRenderer.send('update-action', what),
});
